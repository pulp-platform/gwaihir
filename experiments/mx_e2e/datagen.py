# Generates the inputs of `mx_e2e.c`: FP32 A [M][K] and B [N][K]

import argparse
from pathlib import Path

import numpy as np

M, N, K = 128, 64, 64
SEED = 42


def gen(rows, cols, rng):
    # +-1.m * 2^(e + s): m in {0,.25,.5,.75}, e in {0,1}, s per 32-block in {-1,0,1}
    mant = 1 + rng.integers(0, 4, (rows, cols)) / 4
    exp = rng.integers(0, 2, (rows, cols))
    blk = np.repeat(rng.integers(-1, 2, (rows, cols // 32)), 32, axis=1)
    sign = rng.choice([-1.0, 1.0], (rows, cols))
    return (sign * mant * np.exp2(exp + blk)).astype(np.float32)


def c_array(ctype, name, vals):
    body = ',\n'.join('    ' + ', '.join(repr(float(v)) + 'f' for v in vals[i:i + 8])
                      for i in range(0, len(vals), 8))
    return f'{ctype} {name}[{len(vals)}] __attribute__((aligned(64))) = {{\n{body}\n}};\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('-o', '--output', type=Path, required=True)
    args = parser.parse_args()
    rng = np.random.default_rng(SEED)
    a = gen(M, K, rng)
    b = gen(N, K, rng)
    # Every partial sum of C is exact in FP32, so the golden is order independent
    c = a.astype(np.float64) @ b.astype(np.float64).T
    assert np.array_equal(c, c.astype(np.float32).astype(np.float64))
    hdr = [
        '// Copyright 2026 ETH Zurich and University of Bologna.',
        '// Licensed under the Apache License, Version 2.0, see LICENSE for details.',
        '// SPDX-License-Identifier: Apache-2.0',
        '',
        '// Generated by experiments/mx_e2e/datagen.py, do not edit.',
        '',
        '#pragma once',
        '',
        f'#define MX_M {M}',
        f'#define MX_N {N}',
        f'#define MX_K {K}',
        '',
        c_array('float', 'mx_a', a.flatten()),
        c_array('float', 'mx_b', b.flatten()),
    ]
    args.output.write_text('\n'.join(hdr))


if __name__ == '__main__':
    main()
